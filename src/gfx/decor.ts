/**
 * Mais enfeites de cenário (segunda leva): objetos encostados nas paredes (urnas, lápides, caixotes,
 * barris, braseiros), detalhes de chão (velas, rachaduras, cristais, cogumelos, conchas, obsidiana)
 * e de parede (nichos com vela, placas, veios de minério, vinhas, runas, lava escorrendo).
 * Os orgânicos (rachaduras, vinhas, limo, raízes, capim) são procedurais, com variação pelo tema.
 */

const T = 16;
const pc = (ch: string): RGBA => hex(PAL[ch]);
const blank = (): Pixmap => new Pixmap(T, T);
const g = (name: string, block: string): Pixmap => fromRows(rowsOf(block), PAL, name, T);
/** Troca as cores de um bloco de texto antes de montar (quadros de animação). */
const gs = (name: string, block: string, swap: Record<string, string>): Pixmap =>
  g(name, block.replace(/[^\n]/g, (ch) => swap[ch] ?? ch));

