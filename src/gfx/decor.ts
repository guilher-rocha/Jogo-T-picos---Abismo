export function makeDecor(style: TerrainStyle): Record<string, Pixmap[]> {
  const s = style.seed;
  const out: Record<string, Pixmap[]> = {};
  const mortar = hex(style.wall.mortar);
  const wallLight = hex(style.wall.light);
  const floorDark = darken(hex(style.floor.dark), 0.45);
  const floorLight = hex(style.floor.light);
  // parede
  out.candle_niche = NICHE_FLAMES.map((f) => gs('candle_niche', CANDLE_NICHE, f));
  out.plaque = [g('plaque', PLAQUE)];
  out.ore_vein = [g('ore_vein', ORE_VEIN)];
  out.support_beam = [g('support_beam', SUPPORT_BEAM)];
  out.lantern = LANTERN_LIGHT.map((f) => gs('lantern', LANTERN, f).outline(0.6));
  out.pickaxe_wall = [g('pickaxe_wall', PICKAXE_WALL)];
  out.shelf_fungus = [g('shelf_fungus', SHELF_FUNGUS)];
  out.shield_trophy = [g('shield_trophy', SHIELD_TROPHY)];
  out.rune_glow = [gs('rune', RUNE, { F: 'R' }), gs('rune', RUNE, { F: 'q' })];
  out.wall_crack = [crack(s * 3 + 1, darken(mortar, 0.3), mix(wallLight, mortar, 0.3))];
  out.wall_moss = [wallMoss(s * 3 + 2, hex(style.moss))];
  out.vines = [vines(s * 3 + 3, darken(hex(style.moss), 0.35), hex(style.moss))];
  out.drip_stain = [dripStain(s * 3 + 4)];
  out.lava_seep = [lavaCrack(s * 3 + 5, 0, true), lavaCrack(s * 3 + 5, 1, true)];
  // chão
  out.candles = CANDLE_FLAMES.map((f) => gs('candles', CANDLES, f).outline(0.6));
  out.urn = [g('urn', URN)];
  out.tombstone = [g('tombstone', TOMBSTONE)];
  out.broken_pillar = [g('broken_pillar', BROKEN_PILLAR)];
  out.crate = [g('crate', CRATE)];
  out.barrel = [g('barrel', BARREL)];
  out.ore_chunks = [g('ore_chunks', ORE_CHUNKS)];
  out.planks = [g('planks', PLANKS)];
  out.mushrooms = [g('mushrooms', MUSHROOMS)];
  out.crystals = [g('crystals', CRYSTALS)];
  out.shells = [g('shells', SHELLS)];
  out.rusty_helm = [g('rusty_helm', RUSTY_HELM)];
  out.obsidian = [g('obsidian', OBSIDIAN)];
  out.brazier = BRAZIER_FLAMES.map((f) => gs('brazier', BRAZIER, f).outline(0.6));
  out.floor_crack = [crack(s * 5 + 7, floorDark, mix(floorLight, floorDark, 0.4), 3, 13)];
  out.lava_crack = [lavaCrack(s * 5 + 8, 0, false), lavaCrack(s * 5 + 8, 1, false)];
  out.grass = [grass(s * 5 + 9, [darken(hex(style.moss), 0.3), hex(style.moss), lighten(hex(style.moss), 0.3)])];
  out.roots = [roots(s * 5 + 10)];
  out.ash = [ash(s * 5 + 11)];
  out.seaweed = [seaweed(s * 5 + 12)];
  return out;
}
