/** Rachadura: caminho aleatório de cima para baixo com galhos; borda clara do lado de baixo/direita. */
function crack(seed: number, dark: RGBA, edge: RGBA, y0 = 1, y1 = 14): Pixmap {
  const p = blank();
  let x = 5 + Math.floor(hash01(seed, 1) * 6);
  for (let y = y0; y <= y1; y++) {
    p.set(x, y, dark);
    if (p.alpha(x + 1, y) === 0) p.set(x + 1, y, edge);
    const r = hash01(seed, y, 2);
    if (r < 0.3) x--;
    else if (r > 0.7) x++;
    x = Math.max(2, Math.min(13, x));
    // galho curto
    if (hash01(seed, y, 3) < 0.18) {
      const dir = hash01(seed, y, 4) < 0.5 ? -1 : 1;
      for (let k = 1; k <= 3; k++) {
        const bx = x + dir * k;
        const by = y + (k >> 1);
        if (bx < 1 || bx > 14 || by > 15) break;
        p.set(bx, by, dark);
      }
    }
  }
  return p;
}

/** Rachadura brilhante de lava (chão ou parede), com quadros de pulsação. */
function lavaCrack(seed: number, frame: number, wall: boolean): Pixmap {
  const p = blank();
  const hot = frame ? pc('y') : pc('O');
  const core = frame ? pc('Y') : pc('y');
  const rim = pc('r');
  let x = 3 + Math.floor(hash01(seed, 1) * 3);
  let y = wall ? 2 : 4 + Math.floor(hash01(seed, 2) * 3);
  // linha diagonal irregular (chão) ou vertical (parede)
  for (let i = 0; i < 12; i++) {
    p.set(x, y, i % 4 === 1 ? core : hot);
    for (const [dx, dy] of [[0, -1], [0, 1], [-1, 0], [1, 0]] as const) if (p.alpha(x + dx, y + dy) === 0) p.set(x + dx, y + dy, rim);
    const r = hash01(seed, i, 3);
    if (wall) {
      y++;
      if (r < 0.3) x--;
      else if (r > 0.7) x++;
    } else {
      x++;
      if (r < 0.3) y--;
      else if (r > 0.7) y++;
    }
    x = Math.max(1, Math.min(14, x));
    y = Math.max(1, Math.min(14, y));
  }
  // na parede, uma gota pingando no fim
  if (wall) {
    p.set(x, Math.min(15, y + 1), frame ? core : hot);
  }
  return p;
}

/** Limo/musgo pendurado do alto da face da parede. */
function wallMoss(seed: number, color: RGBA): Pixmap {
  const p = blank();
  for (let x = 0; x < T; x++) {
    const len = Math.floor(hash01(seed, x, 1) * 4) + (hash01(seed, x, 2) < 0.2 ? 4 : 0);
    for (let y = 0; y < len; y++) {
      const c = y === len - 1 ? lighten(color, 0.25) : hash01(seed, x * 7 + y, 3) < 0.4 ? darken(color, 0.25) : color;
      p.set(x, y, c);
    }
  }
  return p;
}

/** Vinhas pendendo com folhinhas. */
function vines(seed: number, stem: RGBA, leaf: RGBA): Pixmap {
  const p = blank();
  const n = 3 + Math.floor(hash01(seed, 0) * 2);
  for (let v = 0; v < n; v++) {
    let x = 1 + Math.floor(((v + hash01(seed, v, 1) * 0.6) / n) * 14);
    const len = 6 + Math.floor(hash01(seed, v, 2) * 9);
    for (let y = 0; y < len; y++) {
      p.set(x, y, stem);
      if (y % 3 === 1) {
        const side = (y + v) % 2 ? 1 : -1;
        p.set(x + side, y, leaf);
        p.set(x + side, y + 1, darken(leaf, 0.2));
      }
      if (hash01(seed, v * 31 + y, 3) < 0.25) x += hash01(seed, v * 31 + y, 4) < 0.5 ? -1 : 1;
      x = Math.max(0, Math.min(15, x));
    }
    p.set(x, len, lighten(leaf, 0.2));
  }
  return p;
}

/** Manchas de umidade escorrendo da parede, com gota na ponta. */
function dripStain(seed: number): Pixmap {
  const p = blank();
  const stain = hex('#10283a70');
  const wet = hex('#8ed8f0c0');
  for (let s = 0; s < 3; s++) {
    const x = 2 + Math.floor(hash01(seed, s) * 12);
    const len = 5 + Math.floor(hash01(seed, s, 1) * 9);
    for (let y = 0; y < len; y++) {
      p.set(x, y, stain);
      if (y < len / 2 && hash01(seed, s * 13 + y) < 0.5) p.set(x + 1, y, stain);
    }
    p.set(x, len, wet);
  }
  return p;
}

/** Capim/folhagem rasteira. */
function grass(seed: number, colors: RGBA[]): Pixmap {
  const p = blank();
  const tufts = 2 + Math.floor(hash01(seed, 0) * 2);
  for (let t = 0; t < tufts; t++) {
    const bx = 2 + Math.floor(hash01(seed, t, 1) * 11);
    const by = 9 + Math.floor(hash01(seed, t, 2) * 5);
    for (let b = -1; b <= 1; b++) {
      const h = 2 + Math.floor(hash01(seed, t * 5 + b, 3) * 3);
      for (let y = 0; y < h; y++) {
        const x = bx + b * 1 + (y === h - 1 ? b : 0);
        p.set(x, by - y, colors[Math.min(colors.length - 1, y)]);
      }
    }
  }
  return p;
}

/** Raízes atravessando o chão. */
function roots(seed: number): Pixmap {
  const p = blank();
  const c = pc('c');
  const hi = pc('d');
  for (let r = 0; r < 2; r++) {
    let y = 4 + Math.floor(hash01(seed, r) * 9);
    for (let x = 0; x < T; x++) {
      p.set(x, y, c);
      if (p.alpha(x, y - 1) === 0) p.set(x, y - 1, hi);
      const v = hash01(seed, r * 40 + x, 1);
      if (v < 0.25) y--;
      else if (v > 0.75) y++;
      y = Math.max(2, Math.min(14, y));
      if (x > 5 + r * 4 && hash01(seed, r, 9) < 0.5 && x > 10) break;
    }
  }
  return p;
}

/** Monte de cinzas com brasinhas. */
function ash(seed: number): Pixmap {
  const p = blank();
  for (let y = 8; y < 15; y++) for (let x = 2; x < 14; x++) {
    const d = ((x - 7.5) / 5.5) ** 2 + ((y - 11.5) / 3) ** 2 + (hash01(seed, x * 16 + y) - 0.5) * 0.5;
    if (d < 1) p.set(x, y, hash01(seed, x, y) < 0.5 ? hex('#4a4450') : hex('#6a626e'));
  }
  p.set(6, 11, pc('O'));
  p.set(9, 12, pc('o'));
  return p;
}

/** Algas ondulando para cima (ruínas alagadas). */
function seaweed(seed: number): Pixmap {
  const p = blank();
  const cols = [pc('t'), pc('T'), hex('#5aa080')];
  for (let s = 0; s < 3; s++) {
    const bx = 3 + s * 4 + Math.floor(hash01(seed, s) * 2);
    const h = 5 + Math.floor(hash01(seed, s, 1) * 5);
    for (let y = 0; y < h; y++) {
      const x = bx + Math.round(Math.sin(y * 0.9 + s) * 1);
      p.set(x, 14 - y, cols[Math.min(2, Math.floor((y / h) * 3))]);
    }
  }
  return p;
}

